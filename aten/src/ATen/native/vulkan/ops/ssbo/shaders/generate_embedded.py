        with tempfile.TemporaryDirectory() as temp_dir:
            spv_silu = Path(temp_dir) / "conv2d_x32v4acc_silu_fp16.spv"
            spv_silu_f32 = Path(temp_dir) / "conv2d_x32v4acc_silu_f32o_fp16.spv"
            compile_shader(args.compiler, source_silu, spv_silu, f32_out=False)
