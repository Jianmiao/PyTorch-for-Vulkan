#!/usr/bin/env python3
"""Compile SSBO shaders and generate their C++ byte-array headers."""

from __future__ import annotations

import argparse
import subprocess
import tempfile
from pathlib import Path


def compile_shader(compiler: Path, source: Path, output: Path, f32_out: bool) -> None:
    command = [
        str(compiler),
        "-V",
        "--target-env",
        "vulkan1.1",
        "-S",
        "comp",
    ]
    if f32_out:
        command.append("-DF32_OUT")
    command.extend(["-o", str(output), str(source)])
    subprocess.run(command, check=True)


def array_definition(symbol: str, data: bytes) -> str:
    rows = []
    for offset in range(0, len(data), 24):
        rows.append("  " + ", ".join(str(value) for value in data[offset : offset + 24]))
    body = ",\n".join(rows)
    return (
        f"static const uint8_t {symbol}[] = {{\n{body}\n}};\n"
        f"static const size_t {symbol}_size = {len(data)};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--compiler", type=Path, required=True)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("conv2d_simple_spv.h"),
    )
    parser.add_argument(
        "--conv3d-output",
        type=Path,
        default=None,
        help="Also generate the generic Conv3D dilation header.",
    )
    parser.add_argument(
        "--upsample-output",
        type=Path,
        default=None,
        help="Also generate the upsample mode-selecting header.",
    )
    parser.add_argument(
        "--conv2d-x32-output",
        type=Path,
        default=None,
        help="Also generate the fast 32-output-channel Conv2D header.",
    )
    parser.add_argument(
        "--conv2d-x32c32-output",
        type=Path,
        default=None,
        help="Also generate the fast Conv2D header with 32 input channels per chunk.",
    )
